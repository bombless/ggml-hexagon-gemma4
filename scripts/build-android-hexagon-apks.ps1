param(
    [string]$Upstream = "D:\mcp-agent-workspace\ggml-hexagon",
    [string]$SdkRoot = $env:HEXAGON_SDK_ROOT,
    [string]$Output = "artifacts\apk",
    [ValidateSet("all", "fastrpc-mempool", "dspqueue")][string]$OnlyBackend = "all",
    [ValidateSet("all", "native", "kotlin")][string]$BuildStage = "all",
    [switch]$ForceNativeRebuild
)

$ErrorActionPreference = "Stop"
$Repo = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$Upstream = (Resolve-Path $Upstream).Path
$AllowedCommits = @(
    "a5e6be5e032eaf22e6a1154e2b6ab34a76a13a8d", # pinned upstream base
    "14160d08bb789fdaa45c9f9a3c6abc41115bf4ab", # accepted follow-up commit
    "bcdc7eeb441171ed0182701be3e01ea4769947ed", # FastRPC repacking optimization
    "d70860568a59bf2cacf98e0679457f129b9d5b2a", # local runtime-directory patch on top of the pinned base
    "f1c102e9e2a2898408cbc0bff006dc01b913a396" # app-private runtime + DSP cache diagnostic config
)
$ActualCommit = (& git -C $Upstream rev-parse HEAD).Trim()
if ($LASTEXITCODE -ne 0 -or $ActualCommit -notin $AllowedCommits) {
    throw "Upstream checkout must be one of the allowed commits: $($AllowedCommits -join ', ') (found $ActualCommit)."
}
if ([string]::IsNullOrWhiteSpace($SdkRoot) -or !(Test-Path (Join-Path $SdkRoot "build\cmake\hexagon_arch.cmake"))) {
    throw "Set HEXAGON_SDK_ROOT to the licensed Qualcomm Hexagon SDK 6.7.0.0 installation."
}
$SdkConfig = Join-Path $SdkRoot "hexagon_sdk.json"
if (!(Test-Path $SdkConfig)) {
    throw "Hexagon SDK metadata not found: $SdkConfig"
}
$SdkMetadata = Get-Content $SdkConfig -Raw | ConvertFrom-Json
$ToolsRelative = $SdkMetadata.root.tools.info[0].path
if ([string]::IsNullOrWhiteSpace($ToolsRelative)) {
    throw "Hexagon SDK metadata does not declare the bundled Hexagon Tools path."
}
$ToolsRoot = Join-Path $SdkRoot $ToolsRelative
$HexagonCompiler = Join-Path $ToolsRoot "Tools\bin\hexagon-clang.exe"
if (!(Test-Path $HexagonCompiler -PathType Leaf)) {
    throw "Bundled Hexagon compiler not found: $HexagonCompiler (SDK metadata path: $ToolsRelative)"
}
Write-Host "Using bundled Hexagon Tools: $ToolsRoot"

$OutputRoot = Join-Path $Repo $Output
New-Item -ItemType Directory -Force -Path $OutputRoot | Out-Null
function Get-Sha256Hex([string]$Path) {
    $stream = [System.IO.File]::OpenRead($Path)
    try {
        $sha = [System.Security.Cryptography.SHA256]::Create()
        try { return ([BitConverter]::ToString($sha.ComputeHash($stream))).Replace('-', '') }
        finally { $sha.Dispose() }
    } finally { $stream.Dispose() }
}
$Variants = @(
    @{ Name = "fastrpc-mempool"; Backend = "fastrpc-mempool" },
    @{ Name = "dspqueue"; Backend = "dspqueue" }
)
if ($OnlyBackend -ne "all") { $Variants = @($Variants | Where-Object { $_.Name -eq $OnlyBackend }) }
if ($BuildStage -ne "all" -and $OnlyBackend -eq "all") {
    throw "BuildStage '$BuildStage' requires -OnlyBackend fastrpc-mempool or dspqueue. Build each transport separately so its native outputs cannot be overwritten by the other transport."
}
if ($ForceNativeRebuild -and $BuildStage -ne "native") {
    throw "-ForceNativeRebuild can only be used with -BuildStage native."
}

Push-Location $Repo
try {
    foreach ($Variant in $Variants) {
        Write-Host "=== Building $($Variant.Name) ==="
        $GradleArgs = @(
            "--no-daemon",
            "-PggmlHexagonSource=$Upstream",
            "-PggmlHexagonBackend=$($Variant.Backend)",
            "-PhexagonSdkRoot=$SdkRoot",
            "-PhexagonToolsRoot=$ToolsRoot"
        )

        switch ($BuildStage) {
            "native" {
                Write-Host "Building C/C++ only; Kotlin and APK packaging are skipped."
                if ($ForceNativeRebuild) {
                    $NativeBuildCache = Join-Path $Repo "app\.cxx"
                    if (Test-Path $NativeBuildCache) {
                        Write-Host "Force rebuild requested; removing native CMake/Ninja cache: $NativeBuildCache"
                        Remove-Item $NativeBuildCache -Recurse -Force
                    } else {
                        Write-Host "Force rebuild requested; no existing native cache found."
                    }
                }
                & .\gradlew.bat @GradleArgs :app:externalNativeBuildDebug
                if ($LASTEXITCODE -ne 0) { throw "Native build failed for $($Variant.Name)." }
            }
            "kotlin" {
                Write-Host "Building Kotlin and packaging only; the existing C/C++ outputs are reused."
                # mergeDebugAssets has an explicit dependency on the native task
                # because the DSP skeleton is generated by CMake. Excluding the
                # aggregate task keeps this stage from invoking CMake again.
                & .\gradlew.bat @GradleArgs :app:assembleDebug -x :app:externalNativeBuildDebug
            }
            default {
                # Gradle/CMake/Ninja already perform incremental native builds.
                # Keep app/.cxx so unchanged C/C++ translation units are reused.
                & .\gradlew.bat @GradleArgs :app:assembleDebug
            }
        }
        if ($LASTEXITCODE -ne 0) { throw "Gradle $BuildStage build failed for $($Variant.Name)." }

        if ($BuildStage -eq "native") { continue }

        $Apk = Join-Path $Repo "app\build\outputs\apk\debug\app-debug.apk"
        if (!(Test-Path $Apk)) { throw "APK missing for $($Variant.Name)." }
        $Listing = & jar tf $Apk
        if ($LASTEXITCODE -ne 0) { throw "Unable to inspect APK $Apk." }
        foreach ($Required in @(
            "lib/arm64-v8a/libgemma4_jni.so",
            "lib/arm64-v8a/libggml-hexagon.so",
            "assets/hexagon/dsp/libggml-htp-v75.so",
            "assets/hexagon/backend.properties"
        )) {
            if ($Listing -notcontains $Required) { throw "$($Variant.Name) APK lacks $Required" }
        }
        if ($Variant.Name -eq "fastrpc-mempool" -and $Listing -notcontains "assets/hexagon/ap/ggml-hexagon.cfg") {
            throw "FastRPC APK lacks assets/hexagon/ap/ggml-hexagon.cfg"
        }
        if ($Variant.Name -eq "dspqueue" -and $Listing -contains "assets/hexagon/ap/ggml-hexagon.cfg") {
            throw "dspqueue APK contains a stale FastRPC-only ggml-hexagon.cfg asset"
        }
        Copy-Item $Apk (Join-Path $OutputRoot "gemma4-$($Variant.Name)-debug.apk") -Force
        $Artifact = Join-Path $OutputRoot "gemma4-$($Variant.Name)-debug.apk"
        Write-Host "SHA256 $Artifact $(Get-Sha256Hex $Artifact)"
    }
} finally {
    Pop-Location
}

if ($BuildStage -eq "native") {
    Write-Host "Native build completed for $OnlyBackend. Run again with -BuildStage kotlin to package the APK without rebuilding C/C++."
} else {
    Write-Host "Selected transport APK package-content checks passed: $OutputRoot"
}